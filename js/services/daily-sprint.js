class DailySprintService {
  constructor() {
    this._state = storage.get(DAILY_STORAGE_KEY, {
      lastCompletedDate: null,
      currentStreak: 0,
      history: []
    });
  }

  getTodayDateString() {
    const now = new Date();
    const year = now.getFullYear();
    const month = String(now.getMonth() + 1).padStart(2, '0');
    const day = String(now.getDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
  }

  getYesterdayDateString() {
    const yesterday = new Date(Date.now() - 86400000);
    const year = yesterday.getFullYear();
    const month = String(yesterday.getMonth() + 1).padStart(2, '0');
    const day = String(yesterday.getDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
  }

  getTodayChallenge() {
    // Deterministic calendar seeding based on UTC day count
    const epochDays = Math.floor(Date.now() / 86400000);
    const index = Math.abs(epochDays) % DAILY_CHALLENGES.length;
    return DAILY_CHALLENGES[index];
  }

  isCompletedToday() {
    return this._state.lastCompletedDate === this.getTodayDateString();
  }

  getStreak() {
    const today = this.getTodayDateString();
    const yesterday = this.getYesterdayDateString();

    if (this._state.lastCompletedDate === today) {
      return this._state.currentStreak;
    } else if (this._state.lastCompletedDate === yesterday) {
      return this._state.currentStreak;
    } else {
      // Streak broken
      return 0;
    }
  }

  recordCompletion(score, maxScore, challengeId) {
    const today = this.getTodayDateString();
    const yesterday = this.getYesterdayDateString();

    let newStreak = 1;
    if (this._state.lastCompletedDate === yesterday) {
      newStreak = (this._state.currentStreak || 0) + 1;
    } else if (this._state.lastCompletedDate === today) {
      newStreak = this._state.currentStreak || 1;
    }

    this._state.lastCompletedDate = today;
    this._state.currentStreak = newStreak;
    this._state.history.unshift({
      date: today,
      challengeId,
      score,
      maxScore,
      timestamp: Date.now()
    });

    if (this._state.history.length > 30) {
      this._state.history = this._state.history.slice(0, 30);
    }

    storage.set(DAILY_STORAGE_KEY, this._state);
    return newStreak;
  }
}

export const dailySprint = new DailySprintService();
